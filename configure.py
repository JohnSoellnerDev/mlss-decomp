#!/usr/bin/env python3
"""Generate build.ninja, the linker script and objdiff.json from config/.

    python3 configure.py && ninja            # mlss.gba, checked against config/rom.sha1
    ninja report                             # build/report.json (progress)

Layout of the ROM (config/units.txt): code units in ROM order, data in between. A code unit
is built from src/UNIT.c when that file exists, otherwise from the original assembly in
asm/UNIT/*.s (one file per function). Data still comes from baserom.gba (.incbin).

asm/ is not in the repository: it is disassembled from baserom.gba here whenever
config/symbols.txt, config/units.txt or tools/disasm.py changed (tools/unitbuild.py).

Objects per code unit:
  build/expected/UNIT.o  all functions from asm/UNIT/ (the target objdiff compares against)
  build/src/UNIT.o       src/UNIT.c; not yet decompiled functions come in via ASM_FUNC
  build/report/UNIT.o    src/UNIT.c without the ASM_FUNC functions (objdiff's base: only
                         real C counts as decompiled)
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from symbols import binutil, load_symbols, load_units  # noqa: E402
from unitbuild import ASM_INPUTS, expected_source, generate_asm  # noqa: E402

ROM_START, ROM_SIZE = 0x08000000, 0x01000000
AGBCC_FLAGS = "-mthumb-interwork -Wimplicit -Wparentheses -Werror -O2 -fhex-asm"
CATEGORIES = [("game", "Game"), ("sound", "Sound engine"), ("lib", "Library")]


def category(unit):
    return unit.split("/")[0].split("_")[0] if unit.split("_")[0] in ("sound", "lib") else "game"


def main():
    syms = load_symbols(os.path.join(ROOT, "config/symbols.txt"))
    units = load_units(os.path.join(ROOT, "config/units.txt"))
    os.makedirs(os.path.join(ROOT, "build"), exist_ok=True)
    generate_asm()

    # ROM segments: code units and the data between them
    segs, pos = [], ROM_START
    for start, end, name in units:
        if start < pos:
            sys.exit(f"config/units.txt: {name} overlaps the unit before it")
        if start > pos:
            segs.append(("data", pos, start, f"data_{pos:08X}"))
        segs.append(("code", start, end, name))
        pos = end
    if pos < ROM_START + ROM_SIZE:
        segs.append(("data", pos, ROM_START + ROM_SIZE, f"data_{pos:08X}"))

    in_code = lambda a: any(s <= a < e for _, s, e, _n in segs if _ == "code")
    funcs = {name: [s for a, s in sorted(syms.items()) if start <= a < end and s.is_func]
             for start, end, name in units}

    gen = lambda *p: os.path.join(ROOT, "build", *p)
    write_if_changed = _write_if_changed

    # data units: bytes from baserom.gba
    for kind, start, end, name in segs:
        if kind == "data":
            write_if_changed(gen("data", name + ".s"),
                             f'\t.section .rodata\n\t.incbin "baserom.gba", 0x{start - ROM_START:X}, 0x{end - start:X}\n')

    # expected objects: the original assembly of each function
    for start, end, name in units:
        write_if_changed(gen("expected", name + ".s"), expected_source(name, funcs[name]))

    # linker script: every segment at its original address; symbols that no object defines
    # (RAM, data inside incbin blobs, functions inside data) are given as absolute addresses
    def link_script(objs):
        out = ["OUTPUT_ARCH(arm)", "SECTIONS", "{", f"\t. = 0x{ROM_START:08X};", "\t.rom :", "\t{"]
        for o in objs:
            out.append(f"\t\t{o}(.text .text.* .rodata .rodata.* .data)")
        out += ["\t}", "\t/DISCARD/ : { *(.comment) *(.note.*) }", "}", ""]
        for a, s in sorted(syms.items()):
            if s.is_func and in_code(a):
                continue
            value = a | 1 if s.kind == "thumb" else a
            out.append(f"PROVIDE({s.name} = 0x{value:08X});")
        for a, s in sorted(syms.items()):
            for fl in s.flags:
                if fl.startswith("dup="):
                    out.append(f"PROVIDE({fl[4:]} = 0x{(a | 1 if s.kind == 'thumb' else a):08X});")
        return "\n".join(out) + "\n"

    rom_objs, exp_objs = [], []
    for kind, start, end, name in segs:
        if kind == "data":
            rom_objs.append(f"build/data/{name}.o")
            exp_objs.append(f"build/data/{name}.o")
        else:
            has_c = os.path.exists(os.path.join(ROOT, "src", name + ".c"))
            rom_objs.append(f"build/src/{name}.o" if has_c else f"build/expected/{name}.o")
            exp_objs.append(f"build/expected/{name}.o")
    write_if_changed(gen("ld_script.ld"), link_script(rom_objs))
    write_if_changed(gen("ld_script_expected.ld"), link_script(exp_objs))

    # ninja
    n = []
    n += ["# generated by configure.py", "ninja_required_version = 1.10", "",
          f"AS = {tool('as')}", f"LD = {tool('ld')}", f"OBJCOPY = {tool('objcopy')}",
          "PYTHON = python3", f"AGBCC_FLAGS = {AGBCC_FLAGS}", "",
          "rule configure", "  command = $PYTHON configure.py", "  generator = 1",
          "  description = configure", "",
          "rule as", "  command = $AS -mcpu=arm7tdmi -I . --MD $out.d -o $out $in",
          "  depfile = $out.d", "  deps = gcc", "  description = as $in", "",
          "rule cc", "  command = $PYTHON tools/agbcc.py $flags -o $out $in",
          "  depfile = $out.d", "  deps = gcc", "  description = cc $in $flags", "",
          "rule link", "  command = $LD -T $script -Map $map -o $out", "  description = link $out", "",
          "rule objcopy", "  command = $OBJCOPY -O binary $in $out", "  description = objcopy $out", "",
          "rule check", "  command = $PYTHON tools/check_rom.py $in && touch $out",
          "  description = check $in", "",
          "rule report", "  command = tools/objdiff-cli report generate -o $out",
          "  description = objdiff report", ""]
    config_files = sorted(set(ASM_INPUTS) | {"configure.py", "tools/unitbuild.py"})
    src_dirs = sorted({os.path.dirname(os.path.join("src", u[2] + ".c")) for u in units})
    n += [f"build build.ninja: configure | {' '.join(config_files)} " + " ".join(d for d in src_dirs if os.path.isdir(os.path.join(ROOT, d))), ""]

    report_objs = []
    for kind, start, end, name in segs:
        if kind == "data":
            n.append(f"build build/data/{name}.o: as build/data/{name}.s | baserom.gba")
            continue
        n.append(f"build build/expected/{name}.o: as build/expected/{name}.s")
        if os.path.exists(os.path.join(ROOT, "src", name + ".c")):
            n.append(f"build build/src/{name}.o: cc src/{name}.c")
            n.append(f"  flags = ")
            n.append(f"build build/report/{name}.o: cc src/{name}.c")
            n.append(f"  flags = --report")
            report_objs.append(f"build/report/{name}.o")
    n.append("")
    n += ["build build/mlss.elf: link | build/ld_script.ld " + " ".join(rom_objs),
          "  script = build/ld_script.ld", "  map = build/mlss.map",
          "build mlss.gba: objcopy build/mlss.elf",
          "build build/mlss.ok: check mlss.gba",
          "build build/expected.elf: link | build/ld_script_expected.ld " + " ".join(exp_objs),
          "  script = build/ld_script_expected.ld", "  map = build/expected.map",
          "build build/expected.gba: objcopy build/expected.elf",
          "build build/expected.ok: check build/expected.gba",
          "build build/report.json: report | objdiff.json " + " ".join(
              [f"build/expected/{u[2]}.o" for u in units] + report_objs),
          "build rom: phony build/mlss.ok",
          "build expected: phony build/expected.ok",
          "build report: phony build/report.json",
          "build objects: phony " + " ".join([f"build/expected/{u[2]}.o" for u in units] + report_objs),
          "default rom", ""]
    with open(os.path.join(ROOT, "build.ninja"), "w") as f:  # always: ninja checks its mtime
        f.write("\n".join(n))

    # objdiff
    cfg = {
        "$schema": "https://raw.githubusercontent.com/encounter/objdiff/main/config.schema.json",
        "custom_make": "ninja",
        "custom_args": [],
        "build_target": False,
        "build_base": True,
        "watch_patterns": ["*.c", "*.h", "*.s", "*.inc"],
        "units": [],
        "progress_categories": [{"id": i, "name": t} for i, t in CATEGORIES],
    }
    for start, end, name in units:
        unit = {"name": name, "target_path": f"build/expected/{name}.o",
                "metadata": {"progress_categories": [category(name)], "auto_generated": False}}
        src = os.path.join(ROOT, "src", name + ".c")
        if os.path.exists(src):
            unit["base_path"] = f"build/report/{name}.o"
            unit["metadata"]["source_path"] = f"src/{name}.c"
            # complete: the unit is C only, no original assembly left
            text = open(src).read()
            unit["metadata"]["complete"] = not any(k in text for k in ("ASM_FUNC(", "NONMATCH(", ".include"))
        cfg["units"].append(unit)
    write_if_changed(os.path.join(ROOT, "objdiff.json"), json.dumps(cfg, indent=2) + "\n")


def tool(name):
    """arm-none-eabi-NAME for build.ninja: tools/binutils (relative path) or the one on PATH."""
    path = binutil(name, ROOT)
    return os.path.relpath(path, ROOT) if os.path.isabs(path) else path


def _write_if_changed(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if os.path.exists(path) and open(path).read() == text:
        return
    with open(path, "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
